#!/usr/bin/env python
"""Shrink a full plume/wind dataset into a small version that can be committed to git.

Input: the pickles written by tamagotchi/sim_cli.py
    {data_dir}/puff_data_{dataset}.pickle
    {data_dir}/wind_data_{dataset}.pickle

Output: same file names under --out-dir (default: testdata/ at the repo root,
which is NOT covered by .gitignore, unlike data/). The mini files keep the
full 100 Hz tidx grid and the original time/tidx values, so they load through
data_util.load_plume unchanged:

    from tamagotchi.data_util import load_plume
    puffs, wind = load_plume('constantx5b5', data_dir='testdata/')

The default window [57, 104] s covers the training defaults
(t_val_min=60 .. t_val_max=103, see PlumeEnvironment_v2.__init__) and the
eval t_val_min=58 for switch datasets, with 1 s of margin on both sides for
the tidx-1 lookback in reset(). Poisson datasets need the full span instead:
use --t-start 9 --t-end 120 for poisson_noisy3x5b5 / poisson_mag_narrow_noisy3x5b5.

Example:
    python scripts/make_mini_dataset.py \
        --dataset constantx5b5 \
        --data-dir /src/data/published_results/reproduce/ \
        --out-dir testdata/

Only needs numpy + pandas (does not import tamagotchi).
"""
import argparse
import os

import numpy as np
import pandas as pd

# On-disk schemas written by sim_cli.py / sim_utils.py. Everything else
# (x_minus_radius, concentration, ...) is derived inside load_plume and must
# not be stored.
PUFF_COLS = ['puff_number', 'time', 'x', 'y', 'radius', 'tidx']
WIND_COLS = ['wind_x', 'wind_y', 'time', 'tidx']
ENV_DT_INTS = [2, 4, 5, 10]  # int(env_dt*100) values accepted by load_plume

GITHUB_WARN_MB = 50.0
GITHUB_HARD_MB = 100.0


def enforce_dtypes(df):
    """Same convention as the sim_utils writers: *time* columns float64,
    all other float columns float16, integer columns int."""
    for col in df.columns:
        if 'time' in col:
            n_unique = df[col].nunique()
            df[col] = df[col].astype(np.float64)
            assert df[col].nunique() == n_unique
        elif col in ('tidx', 'puff_number'):
            df[col] = df[col].astype(int)
        elif pd.api.types.is_float_dtype(df[col]):
            df[col] = df[col].astype(np.float16)
    return df


def shrink(puffs, wind, t_start, t_end, puff_keep, seed):
    puffs = puffs[PUFF_COLS].copy()  # drop any derived columns
    wind = wind[WIND_COLS].copy()

    puffs = puffs.query('@t_start <= time <= @t_end')
    wind = wind.query('@t_start <= time <= @t_end')

    if puff_keep < 1.0:
        keep = puffs['puff_number'].unique()
        rng = np.random.RandomState(seed)
        keep = rng.choice(keep, size=int(np.ceil(puff_keep * len(keep))), replace=False)
        puffs = puffs.query('puff_number in @keep')

    puffs = enforce_dtypes(puffs.reset_index(drop=True))
    wind = enforce_dtypes(wind.reset_index(drop=True))
    return puffs, wind


def validate(puffs, wind):
    assert list(puffs.columns) == PUFF_COLS, f"puff columns {list(puffs.columns)}"
    assert list(wind.columns) == WIND_COLS, f"wind columns {list(wind.columns)}"
    assert puffs['time'].dtype == np.float64 and wind['time'].dtype == np.float64
    assert puffs['x'].dtype == np.float16 and puffs['y'].dtype == np.float16
    assert puffs['radius'].dtype == np.float16
    assert wind['wind_x'].dtype == np.float16 and wind['wind_y'].dtype == np.float16

    # tidx must stay on the original 100 Hz grid: tidx == round(time*100)
    assert (wind['tidx'] == np.round(wind['time'] * 100).astype(int)).all(), \
        "wind tidx != round(time*100)"
    assert (puffs['tidx'] == np.round(puffs['time'] * 100).astype(int)).all(), \
        "puff tidx != round(time*100)"

    # wind must be a contiguous 100 Hz timeline within the window
    wtidx = wind['tidx'].to_numpy()
    assert (np.diff(wtidx) == 1).all(), "wind tidx grid has gaps"

    # every wind tidx needs puff rows (puff_indices_by_tidx[self.tidx] KeyErrors
    # otherwise), on the full grid and on every env_dt downsampled grid
    ptidx = set(puffs['tidx'].unique())
    missing = [t for t in wtidx if t not in ptidx]
    assert not missing, f"{len(missing)} wind tidxs have no puffs, e.g. {missing[:5]}"
    for dt_int in ENV_DT_INTS:
        sub = [t for t in wtidx if t % dt_int == 0]
        assert sub, f"no wind tidx left at env_dt_int={dt_int}"


def size_mb(path):
    return os.path.getsize(path) / 1e6


README = """# Mini plume/wind test datasets

Generated by `scripts/make_mini_dataset.py` from the full simulation output
(`sim_cli.py`), cropped to a small time window so they are small enough to
commit. Same schema and file names as the full datasets, so they load
through the normal path:

```python
from tamagotchi.data_util import load_plume
puffs, wind = load_plume('{dataset}', data_dir='{out_dir}')
```

or point an env at them (e.g. monkeypatch `tamagotchi.config.datadir = '{out_dir}'`
before constructing `PlumeEnvironment_v3`). Keep `t_val_min`/`reset_offset_tmax`
inside the cropped window listed below.

| dataset | time window (s) | puff_keep |
|---------|-----------------|-----------|
"""


def update_readme(out_dir, dataset, t_start, t_end, puff_keep):
    path = os.path.join(out_dir, 'README.md')
    row = f"| {dataset} | [{t_start:g}, {t_end:g}] | {puff_keep:g} |\n"
    if os.path.exists(path):
        lines = open(path).readlines()
        lines = [l for l in lines if not l.startswith(f"| {dataset} ")]
        lines.append(row)
        open(path, 'w').writelines(lines)
    else:
        header = README.format(dataset=dataset, out_dir=out_dir.rstrip('/') + '/')
        open(path, 'w').write(header + row)


def main():
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--dataset', required=True,
                    help="dataset name, e.g. constantx5b5 (reads puff_data_<dataset>.pickle "
                         "and wind_data_<dataset>.pickle)")
    ap.add_argument('--data-dir', required=True, help="directory with the full pickles")
    ap.add_argument('--out-dir', default='testdata/', help="output directory (default: testdata/)")
    ap.add_argument('--t-start', type=float, default=57.0,
                    help="window start in seconds (default 57; poisson datasets need 9)")
    ap.add_argument('--t-end', type=float, default=104.0,
                    help="window end in seconds (default 104; poisson datasets need 120)")
    ap.add_argument('--puff-keep', type=float, default=1.0,
                    help="fraction of puff_numbers to keep, whole trajectories (default 1.0)")
    ap.add_argument('--seed', type=int, default=137, help="RNG seed for --puff-keep")
    args = ap.parse_args()

    puff_in = os.path.join(args.data_dir, f'puff_data_{args.dataset}.pickle')
    wind_in = os.path.join(args.data_dir, f'wind_data_{args.dataset}.pickle')
    puffs = pd.read_pickle(puff_in)
    wind = pd.read_pickle(wind_in)
    print(f"in : puffs {len(puffs):>10,} rows ({size_mb(puff_in):8.1f} MB)  "
          f"time [{puffs['time'].min():.2f}, {puffs['time'].max():.2f}]")
    print(f"in : wind  {len(wind):>10,} rows ({size_mb(wind_in):8.1f} MB)  "
          f"time [{wind['time'].min():.2f}, {wind['time'].max():.2f}]")

    mini_puffs, mini_wind = shrink(puffs, wind, args.t_start, args.t_end,
                                   args.puff_keep, args.seed)
    validate(mini_puffs, mini_wind)

    os.makedirs(args.out_dir, exist_ok=True)
    puff_out = os.path.join(args.out_dir, f'puff_data_{args.dataset}.pickle')
    wind_out = os.path.join(args.out_dir, f'wind_data_{args.dataset}.pickle')
    mini_puffs.to_pickle(puff_out)
    mini_wind.to_pickle(wind_out)
    update_readme(args.out_dir, args.dataset, args.t_start, args.t_end, args.puff_keep)

    print(f"out: puffs {len(mini_puffs):>10,} rows ({size_mb(puff_out):8.1f} MB)  -> {puff_out}")
    print(f"out: wind  {len(mini_wind):>10,} rows ({size_mb(wind_out):8.1f} MB)  -> {wind_out}")

    worst = max(size_mb(puff_out), size_mb(wind_out))
    if worst > GITHUB_HARD_MB:
        print(f"ERROR: {worst:.0f} MB exceeds GitHub's 100 MB file limit — "
              f"shrink the window (--t-start/--t-end) or lower --puff-keep.")
        raise SystemExit(1)
    if worst > GITHUB_WARN_MB:
        print(f"WARNING: {worst:.0f} MB > 50 MB (GitHub warns above this) — "
              f"consider a smaller window or --puff-keep 0.5.")
    print("validation OK")


if __name__ == '__main__':
    main()
